#!/usr/bin/env python3
"""mkfetchlogo.py - generates user/fetch_logo.h, the fir that 'fetch' prints
(host tool, run by hand; the header is committed so the OS build needs no
Python). Reuses the boot banner's rasteriser in logo/mklogo.py so the card
shows the same tree as the banner: 25 columns x 13 text rows, CP437 half
blocks, one (char, VGA attribute) pair per cell.

Usage:  python3 user/mkfetchlogo.py > user/fetch_logo.h
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "logo"))
from mklogo import tbm_fir, half_cell, BLK  # noqa: E402

W, ROWS = 25, 13
art = tbm_fir(w=W, h=2 * ROWS, tiers=5, ss=8)
print("/* fetch_logo.h - generated by user/mkfetchlogo.py, do not edit.")
print(" * The boot-banner fir as (CP437 char, VGA attr) cells for fetch.c. */")
print("#define FLOGO_W %d" % W)
print("#define FLOGO_ROWS %d" % ROWS)
print("static const unsigned char flogo[FLOGO_ROWS][FLOGO_W][2] = {")
for r in range(ROWS):
    cells = []
    for x in range(W):
        ch, fg, bg = half_cell(art[2 * r][x], art[2 * r + 1][x], x, r)
        attr = (bg << 4) | fg if ch != 0x20 else 0
        cells.append("{0x%02x,0x%02x}" % (ch, attr))
    print("    {" + ",".join(cells) + "},")
print("};")
